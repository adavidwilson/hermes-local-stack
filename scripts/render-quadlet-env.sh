#!/usr/bin/env bash
# Render the per-service environment files consumed by the Quadlet units.
#
# Compose reads .env for interpolation and injects only the variables each
# service lists. A shared systemd EnvironmentFile cannot do that: it would put
# every secret into every container. This script writes one file per service,
# with only the keys that service needs, and records the host UID/GID that
# keep-id requires.
#
# Usage: scripts/render-quadlet-env.sh [--env-file .env] [--out-dir DIR]
set -euo pipefail

cd "$(dirname "$0")/.."

env_file=.env
out_dir=deploy/podman/env

while [ $# -gt 0 ]; do
	case "$1" in
		--env-file) env_file=${2:?--env-file needs a value}; shift 2 ;;
		--out-dir) out_dir=${2:?--out-dir needs a value}; shift 2 ;;
		-h|--help) sed -n '2,10p' "$0"; exit 0 ;;
		*) echo "render-quadlet-env: unknown argument: $1" >&2; exit 2 ;;
	esac
done

die() { printf 'render-quadlet-env: %s\n' "$*" >&2; exit 1; }

[ -f "$env_file" ] || die "$env_file not found — copy env.example to .env and fill it in"

# Read KEY=VALUE from the compose-style .env. Supports an optional `export`,
# whitespace around '=', and one pair of matching quotes. Inline comments after
# a value are not stripped (compose only treats them as comments after space).
env_get() {
	local key=$1 line value
	line=$(grep -m1 -E "^[[:space:]]*(export[[:space:]]+)?${key}[[:space:]]*=" "$env_file" || true)
	[ -n "$line" ] || return 1
	value=${line#*=}
	value=${value#"${value%%[![:space:]]*}"}
	value=${value%"${value##*[![:space:]]}"}
	case "$value" in
		\"*\") value=${value#\"}; value=${value%\"} ;;
		\'*\') value=${value#\'}; value=${value%\'} ;;
	esac
	[ -n "$value" ] || return 1
	printf '%s' "$value"
}

require() {
	local key=$1 value
	value=$(env_get "$key") || die "$key is missing or empty in $env_file"
	case "$value" in
		*CHANGE_ME*|*GET_ME_FROM*|*GET_ME*) die "$key still has the placeholder value from env.example" ;;
	esac
	printf '%s' "$value"
}

# systemd EnvironmentFile quoting: wrap every value, escape backslash and quote.
write_env() {
	local file=$1; shift
	local tmp
	tmp=$(mktemp "${file}.XXXXXX")
	{
		printf '# Generated by scripts/render-quadlet-env.sh — do not edit.\n'
		while [ $# -gt 0 ]; do
			local key=$1 value=$2
			shift 2
			case "$value" in
				*$'\n'*) die "$key contains a newline" ;;
			esac
			value=${value//\\/\\\\}
			value=${value//\"/\\\"}
			printf '%s="%s"\n' "$key" "$value"
		done
	} >"$tmp"
	chmod 600 "$tmp"
	mv -f "$tmp" "$file"
}

uid=$(id -u)
gid=$(id -g)

# keep-id maps the host user to the same UID in the container, so HERMES_UID
# must be the host UID. Warn if .env disagrees instead of silently producing a
# container that cannot write the bind mount.
if configured_uid=$(env_get HERMES_UID) && [ "$configured_uid" != "$uid" ]; then
	printf 'render-quadlet-env: warning: HERMES_UID=%s in %s but host uid is %s; using %s\n' \
		"$configured_uid" "$env_file" "$uid" "$uid" >&2
fi
if configured_gid=$(env_get HERMES_GID) && [ "$configured_gid" != "$gid" ]; then
	printf 'render-quadlet-env: warning: HERMES_GID=%s in %s but host gid is %s; using %s\n' \
		"$configured_gid" "$env_file" "$gid" "$gid" >&2
fi

tailscale_key=$(require TAILSCALE_AUTHKEY)
llama_key=$(require LLAMA_API_KEY)
dash_user=$(require DASHBOARD_USERNAME)
dash_pass=$(require DASHBOARD_PASSWORD)

install -d -m 700 "$out_dir"

write_env "$out_dir/tailscale.env" \
	TS_AUTHKEY "$tailscale_key"

write_env "$out_dir/inference.env" \
	LLAMA_API_KEY "$llama_key"

write_env "$out_dir/hermes-web.env" \
	HERMES_UID "$uid" \
	HERMES_GID "$gid" \
	DASHBOARD_USERNAME "$dash_user" \
	DASHBOARD_PASSWORD "$dash_pass" \
	LLAMA_API_KEY "$llama_key"

printf 'render-quadlet-env: wrote %s/{tailscale,inference,hermes-web}.env (0600)\n' "$out_dir"
